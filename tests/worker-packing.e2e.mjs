import { openOrderTool } from './helpers/orderTools.mjs';
// Real cookies, APIs and MongoDB transactions; all traffic is redirected to this
// disposable local server. Never imports server.js or loads the development .env.
import test from "node:test";
import assert from "node:assert/strict";
import mongoose from "mongoose";
import express from "express";
import cors from "cors";
import cookieParser from "cookie-parser";
import { chromium, request } from "playwright";
import User from "../models/userModel.js";
import Order from "../models/orderModel.js";
import Product from "../models/productModel.js";
import Slot from "../models/slotModel.js";
import SlotItem from "../models/slotItemModel.js";
import OrderAllocation from "../models/orderAllocationModel.js";
import userRoutes from "../routes/userRoutes.js";
import packingRoutes from "../routes/packingRoutes.js";
import orderRoutes from "../routes/orderRoutes.js";
import siteSettingsRoutes from "../routes/siteSettingsRoutes.js";
import { errorHandler } from "../middleware/errorMiddleware.js";

const uri = process.env.PACKING_E2E_URI;
const frontend = process.env.PACKING_TEST_ORIGIN || "http://localhost:5173";
test("real worker picking, packing and admin confirmed-return deletion against an isolated local API/database", { skip: !uri, timeout: 60000 }, async t => {
  assert.match(uri, /^mongodb:\/\/127\.0\.0\.1:\d+\/megadie_packing_e2e_test(?:\?|$)/);
  assert.match(frontend, /^http:\/\/localhost:\d+$/);
  process.env.NODE_ENV = "test";
  process.env.JWT_SECRET = "local-packing-end-to-end-only";
  let browser, server, owner;
  await mongoose.connect(uri, { autoIndex: false });
  await mongoose.connection.dropDatabase();
  t.after(async () => {
    await browser?.close(); await owner?.dispose();
    if (server) await new Promise(resolve => server.close(resolve));
    await mongoose.connection.dropDatabase(); await mongoose.disconnect();
  });
  await OrderAllocation.createIndexes();
  const admin = await User.create({ name: "Owner", email: "owner@test.invalid", phoneNumber: "owner", password: "test-password", isAdmin: true });
  const worker = await User.create({ name: "Worker Ahmed", email: "worker@test.invalid", phoneNumber: "worker", password: "test-password", isWorker: true });
  const customer = await User.create({ name: "Ahmed Trading", email: "client@test.invalid", phoneNumber: "client", password: "test-password", approvalStatus: "Approved" });
  const productId = new mongoose.Types.ObjectId();
  await Product.collection.insertOne({ _id: productId, name: "Red satin ribbon", sku: "RIB-RED-25MM", packingUnit: "100yd Roll", cbm: 1 });
  const [source, target] = await Slot.create([{ store: "AE1", unit: "A", position: 1, cbm: 1000 }, { store: "AE1", unit: "B", position: 2, cbm: 1000 }]);
  await SlotItem.collection.insertMany([{ product: productId, slot: source._id, qty: 20, cbm: 20 }, { product: productId, slot: target._id, qty: 10, cbm: 10 }]);
  const order = await Order.create({ user: customer._id, status: "Shipping", orderItems: [{ product: productId, sku: "RIB-RED-25MM", qty: 10, unitPrice: 12 }], totalPrice: 120, allocationStatus: "Allocated" });
  const deliveryContact = { contactName: 'Warehouse recipient', phoneNumber: '+971 50 123 4567', secondaryPhoneNumber: '04 123 4567', address: 'Recipient warehouse', googleMapsUrl: '', notes: 'Call on arrival' };
  await Order.updateOne({ _id: order._id }, { $set: { deliveryDetails: deliveryContact } });
  await OrderAllocation.create({ order: order._id, product: productId, slot: source._id, qty: 10, by: admin._id });
  // Exercise real persisted documents that predate the new schema fields.
  await Order.collection.updateOne({ _id: order._id }, { $unset: { packingReports: "", packingActivity: "", packingSummary: "", reservationRevision: "", deliveryRevision: "" } });
  await OrderAllocation.collection.updateMany({ order: order._id }, { $unset: { pickedQty: "", pickProblem: "" } });
  const app = express(); app.use(cors({ origin: frontend, credentials: true }), express.json(), cookieParser());
  app.use("/api/users", userRoutes); app.use("/api/packing", packingRoutes); app.use("/api/orders", orderRoutes); app.use("/api/site-settings", siteSettingsRoutes); app.use(errorHandler);
  server = await new Promise(resolve => { const s = app.listen(0, () => resolve(s)); });
  const api = `http://localhost:${server.address().port}/api`;
  owner = await request.newContext({ extraHTTPHeaders: { Origin: frontend } });
  const login = await owner.post(`${api}/users/auth`, { data: { email: admin.email, password: "test-password" } });
  assert.equal(login.status(), 200);
  const before = (await (await owner.get(`${api}/packing/orders/${order._id}`)).json()).data;
  const sent = await owner.post(`${api}/packing/orders/${order._id}/send`, { data: { workerId: String(worker._id), preparationMode: "prepare_only", deliveryDetails: {}, expectedRevision: before.version, expectedDeliveryRevision: before.deliveryRevision } });
  assert.equal(sent.status(), 200, await sent.text());
  assert.deepEqual((await sent.json()).data.deliveryDetails, deliveryContact);
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await context.route("**/*", async route => {
    const url = new URL(route.request().url());
    if (url.pathname.startsWith("/api/")) return route.continue({ url: `http://localhost:${server.address().port}${url.pathname}${url.search}` });
    return url.origin === frontend ? route.continue() : route.abort();
  });
  const page = await context.newPage(); page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${frontend}/login`);
  await page.getByLabel("Email", { exact: true }).fill(worker.email);
  await page.getByLabel("Password", { exact: true }).fill("test-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("heading", { name: "My work", exact: true }).waitFor();
  await page.getByRole("link", { name: /^Start packing for/ }).click();
  assert.equal(await page.locator('a[href^="tel:"]').count(), 0);
  await page.getByRole("button", { name: "Not enough here", exact: true }).click();
  await page.getByLabel("How many did you take this time?", { exact: true }).fill("6");
  await page.getByRole("button", { name: "Continue at B2-AE1 — 4 × 100yd Roll", exact: true }).click();
  await page.getByRole("button", { name: /^Picked (all|remaining) /, exact: true }).click();
  await page.getByRole("button", { name: "Mark packed", exact: true }).click();
  await page.getByText(/^Packed by Worker Ahmed/).waitFor();
  await page.reload(); await page.getByText(/^Packed by Worker Ahmed/).waitFor();
  const saved = await Order.findById(order._id).select("+packingReports");
  assert.ok(saved.packedAt); assert.equal(saved.packingSummary.collectedItems, 1);
  assert.equal(saved.packingReports[0].shortQty, 4);
  const rows = await OrderAllocation.find({ order: order._id }).sort({ qty: -1 }).lean();
  assert.deepEqual(rows.map(row => [row.qty, row.pickedQty, row.status]), [[6, 6, "Reserved"], [4, 4, "Reserved"]]);
  assert.equal((await SlotItem.findOne({ product: productId, slot: source._id })).qty, 20);
  assert.equal((await SlotItem.findOne({ product: productId, slot: target._id })).qty, 10);
  const packingBeforeDelivery = (await (await owner.get(`${api}/packing/orders/${order._id}`)).json()).data;
  // An older assignment form sends only location fields. Saved contacts must survive.
  const deliveryUpdate = await owner.post(`${api}/packing/orders/${order._id}/send`, { data: { workerId: String(worker._id), preparationMode: 'prepare_deliver', deliveryDetails: { address: 'Updated warehouse', googleMapsUrl: '', notes: 'Ask for recipient' }, expectedRevision: packingBeforeDelivery.version, expectedDeliveryRevision: packingBeforeDelivery.deliveryRevision } });
  assert.equal(deliveryUpdate.status(), 200, await deliveryUpdate.text());
  await page.goto(`${frontend}/packing/deliveries/${order._id}`);
  await page.getByText('Ready to deliver', { exact: true }).waitFor();
  await page.getByText('Warehouse recipient', { exact: true }).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Call recipient', exact: true }).getAttribute('href'), 'tel:+971501234567');
  assert.equal(await page.getByRole('link', { name: 'Call backup', exact: true }).getAttribute('href'), 'tel:041234567');
  assert.equal(await page.getByText('Updated warehouse', { exact: true }).isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '/Users/azad/Developer/megadie/output/worker-delivery-contact-e2e-mobile.png', fullPage: true });
  const adminContext = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
  await adminContext.route("**/*", async route => {
    const url = new URL(route.request().url());
    if (url.pathname.startsWith("/api/")) return route.continue({ url: `http://localhost:${server.address().port}${url.pathname}${url.search}` });
    return url.origin === frontend ? route.continue() : route.abort();
  });
  const adminPage = await adminContext.newPage(); adminPage.setDefaultTimeout(10000);
  adminPage.on("pageerror", error => errors.push(error.message));
  await adminPage.goto(`${frontend}/admin/orders`);
  await adminPage.getByLabel("Email", { exact: true }).fill(admin.email);
  await adminPage.getByLabel("Password", { exact: true }).fill("test-password");
  await adminPage.getByRole("button", { name: "Sign in", exact: true }).click();
  await openOrderTool(adminPage, 'Delete order');
  const dialog = adminPage.getByRole("dialog", { name: "Delete Order", exact: true });
  await dialog.getByText("Picked goods to return", { exact: true }).waitFor();
  await dialog.getByRole("checkbox").check();
  await dialog.getByLabel('Type ' + order.orderNumber + ' to confirm', { exact: true }).fill(order.orderNumber);
  await dialog.getByRole("button", { name: "Delete Order", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await Order.findById(order._id), null);
  assert.equal(await OrderAllocation.countDocuments({ order: order._id }), 0);
  assert.equal((await SlotItem.findOne({ product: productId, slot: source._id })).qty, 20);
  assert.equal((await SlotItem.findOne({ product: productId, slot: target._id })).qty, 10);
  assert.deepEqual(errors, []);
});
